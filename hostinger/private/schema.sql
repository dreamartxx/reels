CREATE TABLE IF NOT EXISTS reels_projects (
 id CHAR(32) PRIMARY KEY, document LONGTEXT NOT NULL, updated_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reels_jobs (
 id CHAR(32) PRIMARY KEY, project_id CHAR(32) NOT NULL, kind VARCHAR(16) NOT NULL,
 status VARCHAR(16) NOT NULL, payload LONGTEXT NOT NULL, result LONGTEXT,
 progress DOUBLE NOT NULL DEFAULT 0, message TEXT NOT NULL,
 cancelled INT NOT NULL DEFAULT 0, lease CHAR(32), heartbeat BIGINT NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL, INDEX queue_index (status, created_at), INDEX project_index(project_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reels_meta (name VARCHAR(80) PRIMARY KEY, value TEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reels_login_attempts (id CHAR(64) PRIMARY KEY, attempts INT NOT NULL, window_start BIGINT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
